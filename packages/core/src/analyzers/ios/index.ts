import type { Analyzer, AnalyzerContext } from '../../shared/types.js'
import type { IosNativeFacts } from './parse.js'
import { parseIosNative } from './parse.js'
import { iosRules } from './rules.js'

/**
 * The model the iOS layer's rules run against.
 *
 * `dependencies` is carried alongside the native facts because the layer's most
 * valuable rule is a cross-reference: a dependency that needs a permission,
 * against the Info.plist keys that are actually present.
 */
export interface IosModel extends IosNativeFacts {
  /** Names of every runtime + dev dependency, for capability cross-referencing. */
  dependencies: Set<string>
}

export const iosAnalyzer: Analyzer<IosModel> = {
  name: 'ios',
  category: 'ios',
  rules: iosRules,

  /**
   * Collect native iOS facts, or skip the layer entirely.
   *
   * As on Android, Continuous Native Generation means most Expo projects have no
   * `ios/` directory at all — it is generated by prebuild/EAS and usually
   * gitignored. That is the COMMON case and must be silent: returning null marks
   * the layer not-applicable so it is excluded from scoring rather than counted
   * as a pass or a failure.
   */
  async collect(ctx: AnalyzerContext): Promise<IosModel | null> {
    const { project, logger, root } = ctx

    if (!project.hasIosDir) {
      logger.debug('no ios/ directory; skipping ios layer (CNG project)')
      return null
    }

    const facts = await parseIosNative(root)

    // Without an Info.plist there is no permission surface to reason about, and
    // the privacy-manifest and Podfile rules alone would give a misleading
    // picture of a directory we could not really read.
    if (!facts.plist) {
      logger.debug('ios/ present but no readable Info.plist was found; skipping ios layer')
      return null
    }

    const pkg = project.packageJson
    const dependencies = new Set<string>([
      ...Object.keys(pkg?.dependencies ?? {}),
      // Dev dependencies count: a native module pulled in for a dev client still
      // ends up in the binary and still needs its purpose string.
      ...Object.keys(pkg?.devDependencies ?? {}),
    ])

    logger.debug(
      `ios layer: ${facts.plist.usageDescriptions.length} usage description(s), ` +
        `privacy manifest ${facts.hasPrivacyManifest ? 'present' : 'absent'}`,
    )

    return { ...facts, dependencies }
  },
}
